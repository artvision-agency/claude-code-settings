#!/bin/bash
# PostToolUse (Bash): после генерации ORM-отзывов — БЛОКИРУЮЩЕЕ напоминание проверить логику
# Инцидент: 2026-03-30 — "два раза заказал, проблем не было, но оформил возврат" (Юрий Хаит поймал)

BASH_CMD="${CLAUDE_BASH_COMMAND:-$1}"

if [ -z "$BASH_CMD" ]; then
  exit 0
fi

# Детектим генерацию отзывов: python + (review/отзыв/orm) + (xlsx/openpyxl)
IS_REVIEW=0
if echo "$BASH_CMD" | grep -qi "python"; then
  if echo "$BASH_CMD" | grep -qi "отзыв\|review\|orm\|размещению"; then
    if echo "$BASH_CMD" | grep -qi "xlsx\|openpyxl\|xlsxwriter"; then
      IS_REVIEW=1
    fi
  fi
fi

if [ "$IS_REVIEW" -eq 0 ]; then
  exit 0
fi

cat << 'CHECKLIST'
🔴 ORM REVIEW CHECK — ОБЯЗАТЕЛЬНО перед показом клиенту/команде:

□ 1. ЛОГИКА: перечитай каждый отзыв — нет ли внутренних противоречий?
□ 2. ТЕМА: отзывы ТОЛЬКО про покупку/визит — НЕ про возвраты/мошенничество/претензии
□ 3. ДЕТАЛИ: нет излишней детализации (артикулы, модели) — пишут как обычные люди
□ 4. ТОЧКИ: упомянуты реальные адреса/ТЦ клиента (если есть)
□ 5. СТИЛЬ: похоже на реальные отзывы конкурентов на этой площадке?

Если хоть один □ не пройден — ПЕРЕПИСАТЬ перед показом.
CHECKLIST

exit 0
