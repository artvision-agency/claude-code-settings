#!/usr/bin/env bash
# install-sf-wrapper.sh — creates `sf` CLI wrapper for Screaming Frog SEO Spider.
# Required because the launcher binary depends on siblings in its .app bundle
# (universalJavaApplicationStub), so a plain symlink breaks.
#
# Usage: ./install-sf-wrapper.sh
# Installs to: ~/.local/bin/sf (must be in $PATH)

set -euo pipefail

APP="/Applications/Screaming Frog SEO Spider.app/Contents/MacOS/ScreamingFrogSEOSpiderLauncher"
TARGET="${HOME}/.local/bin/sf"

if [ ! -x "$APP" ]; then
  echo "ERROR: Screaming Frog not found at $APP" >&2
  echo "Install from https://www.screamingfrog.co.uk/seo-spider/ first." >&2
  exit 1
fi

mkdir -p "$(dirname "$TARGET")"

cat > "$TARGET" <<EOF
#!/usr/bin/env bash
# Auto-generated by install-sf-wrapper.sh. Do not edit manually.
exec "$APP" "\$@"
EOF

chmod +x "$TARGET"
echo "OK: installed $TARGET"

# Sanity check: is ~/.local/bin in PATH?
case ":$PATH:" in
  *":$HOME/.local/bin:"*) ;;
  *) echo "WARN: $HOME/.local/bin is not in PATH. Add it to your shell rc." >&2 ;;
esac

"$TARGET" --help >/dev/null 2>&1 || echo "WARN: sf --help failed; check Java runtime" >&2
