#!/bin/bash
# Cron-напоминание про подачу пакета документов в банк по семейной ипотеке.
# Сценарий: 13.05 чт - проверка прогресса, 14.05 чт - финал доков, 15.05 пт - подача.
# LaunchAgent: ~/Library/LaunchAgents/pro.artvision.ipoteka-reminder.plist
set -euo pipefail

TODAY="$(date +%Y-%m-%d)"
DOW="$(date +%u)"  # 1=Mon..7=Sun

URL="https://artvision.pro/private/ipoteka-583152749426ec33.html"

case "$TODAY" in
  2026-05-14)
    MSG=$'🏦 ИПОТЕКА — четверг 14.05, ЗАВТРА подача\n\nЧек-лист пакета:\n• Паспорт скан\n• Свидетельства о рождении ребёнка и о разводе\n• СНИЛС твой и ребёнка\n• Налоговая декларация 2025 + квитанция приёма\n• Выписка р/с ИП 01.05.25–30.04.26\n• БКИ PDF-файлом\n• Просрочки Альфа/Сбер/Совком — закрыть до подачи\n\nДеталь: '"$URL"
    ;;
  2026-05-15)
    MSG=$'🚨 ИПОТЕКА — пятница 15.05, СЕГОДНЯ ПОДАЧА\n\nПонедельник 18.05 теряет 2 дня (выходные).\nКатя ждёт пакет + первый взнос для расчётов.\n\nДеталь: '"$URL"
    ;;
  2026-05-13)
    MSG=$'🏦 ИПОТЕКА — среда 13.05, t-2 до подачи\n\nСегодня от тебя:\n• Решение по размеру первого взноса (ждёт Катя)\n• Запись в МФЦ Калининского на перепрописку ребёнка\n• Заказ налоговой декларации + выписки ИП\n• БКИ скачать в PDF\n\nДеталь: '"$URL"
    ;;
  *)
    # Скрипт может быть вызван вручную — без MSG ничего не отправляем
    echo "no scheduled message for $TODAY" >&2
    exit 0
    ;;
esac

~/.claude/scripts/tg-send.sh anton "$MSG"
echo "[$(date '+%F %T')] sent ipoteka reminder for $TODAY" >> ~/.claude/logs/ipoteka-reminder.log
